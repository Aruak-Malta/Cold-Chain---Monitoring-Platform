-- Default temperature limits and alerts for broker-created equipment.

BEGIN;

CREATE TABLE IF NOT EXISTS public."Limites" (
  id_limites bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_equipamento bigint NOT NULL,
  temperatura_minima double precision NOT NULL DEFAULT -22,
  temperatura_maxima double precision NOT NULL DEFAULT 12,
  tolerancia_minutos integer NOT NULL DEFAULT 5,
  watchdog_minutos integer NOT NULL DEFAULT 10
);

ALTER TABLE public."Limites"
  ADD COLUMN IF NOT EXISTS temperatura_minima double precision,
  ADD COLUMN IF NOT EXISTS temperatura_maxima double precision,
  ADD COLUMN IF NOT EXISTS tolerancia_minutos integer,
  ADD COLUMN IF NOT EXISTS watchdog_minutos integer;

ALTER TABLE public."Limites"
  ADD COLUMN IF NOT EXISTS id_equipamento bigint,
  ADD COLUMN IF NOT EXISTS id_limites bigint;

UPDATE public."Limites"
SET
  temperatura_minima = COALESCE(temperatura_minima, -22),
  temperatura_maxima = COALESCE(temperatura_maxima, 12),
  tolerancia_minutos = COALESCE(tolerancia_minutos, 5),
  watchdog_minutos = COALESCE(watchdog_minutos, 10);

UPDATE public."Limites"
SET temperatura_maxima = 12
WHERE temperatura_maxima = -12;

ALTER TABLE public."Limites"
  ALTER COLUMN temperatura_minima SET NOT NULL,
  ALTER COLUMN temperatura_minima SET DEFAULT -22,
  ALTER COLUMN temperatura_maxima SET NOT NULL,
  ALTER COLUMN temperatura_maxima SET DEFAULT 12,
  ALTER COLUMN tolerancia_minutos SET NOT NULL,
  ALTER COLUMN tolerancia_minutos SET DEFAULT 5,
  ALTER COLUMN watchdog_minutos SET NOT NULL,
  ALTER COLUMN watchdog_minutos SET DEFAULT 10;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public."Limites"'::regclass
      AND conname = 'cold_ghost_uq_limites_equipamento'
  ) THEN
    ALTER TABLE public."Limites"
      ADD CONSTRAINT cold_ghost_uq_limites_equipamento UNIQUE (id_equipamento);
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public."Avisos" (
  id_aviso bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_equipamento bigint NOT NULL,
  id_limites bigint,
  codigo text NOT NULL,
  nivel text NOT NULL,
  titulo text NOT NULL,
  detalhe text,
  valor text,
  timestamp timestamptz DEFAULT now(),
  reconhecido boolean NOT NULL DEFAULT false
);

ALTER TABLE public."Avisos"
  ADD COLUMN IF NOT EXISTS id_aviso bigint,
  ADD COLUMN IF NOT EXISTS id_equipamento bigint,
  ADD COLUMN IF NOT EXISTS id_limites bigint,
  ADD COLUMN IF NOT EXISTS codigo text,
  ADD COLUMN IF NOT EXISTS nivel text,
  ADD COLUMN IF NOT EXISTS titulo text,
  ADD COLUMN IF NOT EXISTS detalhe text,
  ADD COLUMN IF NOT EXISTS valor text,
  ADD COLUMN IF NOT EXISTS timestamp timestamptz,
  ADD COLUMN IF NOT EXISTS reconhecido boolean;

UPDATE public."Avisos"
SET
  codigo = COALESCE(codigo, 'limite_temperatura'),
  nivel = COALESCE(nivel, 'warning'),
  titulo = COALESCE(titulo, 'Limite de temperatura excedido'),
  timestamp = COALESCE(timestamp, now()),
  reconhecido = COALESCE(reconhecido, false);

ALTER TABLE public."Avisos"
  ALTER COLUMN codigo SET NOT NULL,
  ALTER COLUMN nivel SET NOT NULL,
  ALTER COLUMN titulo SET NOT NULL,
  ALTER COLUMN timestamp SET DEFAULT now(),
  ALTER COLUMN reconhecido SET NOT NULL,
  ALTER COLUMN reconhecido SET DEFAULT false;

INSERT INTO public."Limites" (
  id_equipamento,
  temperatura_minima,
  temperatura_maxima,
  tolerancia_minutos,
  watchdog_minutos
)
SELECT id_equipamento, -22, 12, 5, 10
FROM public."Equipamento"
ON CONFLICT (id_equipamento) DO NOTHING;

CREATE OR REPLACE FUNCTION public.cold_ghost_create_default_limit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public."Limites" (
    id_equipamento,
    temperatura_minima,
    temperatura_maxima,
    tolerancia_minutos,
    watchdog_minutos
  )
  VALUES (NEW.id_equipamento, -22, 12, 5, 10)
  ON CONFLICT (id_equipamento) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS cold_ghost_equipment_default_limit ON public."Equipamento";
CREATE TRIGGER cold_ghost_equipment_default_limit
AFTER INSERT ON public."Equipamento"
FOR EACH ROW
EXECUTE FUNCTION public.cold_ghost_create_default_limit();

CREATE OR REPLACE FUNCTION public.cold_ghost_create_temperature_alert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_limit record;
  v_temperature double precision;
  v_column text;
  v_timestamp timestamptz;
  v_titulo text;
  v_detalhe text;
  v_valor text;
BEGIN
  SELECT l.*
  INTO v_limit
  FROM public."Limites" AS l
  WHERE l.id_equipamento = NEW.id_equipamento;

  IF v_limit.id_equipamento IS NULL THEN
    RETURN NEW;
  END IF;

  v_column := CASE
    WHEN EXISTS (
      SELECT 1 FROM pg_attribute
      WHERE attrelid = 'public."Data"'::regclass
        AND attname = 'temperatura_float'
        AND NOT attisdropped
    ) THEN 'temperatura_float'
    WHEN EXISTS (
      SELECT 1 FROM pg_attribute
      WHERE attrelid = 'public."Data"'::regclass
        AND attname = 'temperatura'
        AND NOT attisdropped
    ) THEN 'temperatura'
    ELSE NULL
  END;

  IF v_column IS NULL THEN
    RETURN NEW;
  END IF;

  BEGIN
    v_temperature := (to_jsonb(NEW)->>v_column)::double precision;
  EXCEPTION WHEN OTHERS THEN
    v_temperature := NULL;
  END;

  IF v_temperature IS NULL THEN
    RETURN NEW;
  END IF;

  IF v_temperature < v_limit.temperatura_minima THEN
    v_titulo := 'Temperatura abaixo do limite';
    v_detalhe := 'A leitura ficou abaixo da temperatura mínima configurada.';
    v_valor := format('%s °C · mínimo %s °C', v_temperature, v_limit.temperatura_minima);
  ELSIF v_temperature > v_limit.temperatura_maxima THEN
    v_titulo := 'Temperatura acima do limite';
    v_detalhe := 'A leitura ultrapassou a temperatura máxima configurada.';
    v_valor := format('%s °C · máximo %s °C', v_temperature, v_limit.temperatura_maxima);
  ELSE
    RETURN NEW;
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public."Avisos"
    WHERE id_equipamento = NEW.id_equipamento
      AND codigo = CASE WHEN v_temperature < v_limit.temperatura_minima THEN 'temperatura_minima' ELSE 'temperatura_maxima' END
      AND reconhecido = false
  ) THEN
    INSERT INTO public."Avisos" (
      id_equipamento,
      id_limites,
      codigo,
      nivel,
      titulo,
      detalhe,
      valor,
      timestamp,
      reconhecido
    )
    VALUES (
      NEW.id_equipamento,
      v_limit.id_limites,
      CASE WHEN v_temperature < v_limit.temperatura_minima THEN 'temperatura_minima' ELSE 'temperatura_maxima' END,
      'warning',
      v_titulo,
      v_detalhe,
      v_valor,
      now(),
      false
    );
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS cold_ghost_temperature_alert ON public."Data";
CREATE TRIGGER cold_ghost_temperature_alert
AFTER INSERT ON public."Data"
FOR EACH ROW
EXECUTE FUNCTION public.cold_ghost_create_temperature_alert();

ALTER TABLE public."Limites" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Avisos" ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public."Limites" FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public."Avisos" FROM PUBLIC, anon, authenticated;
GRANT SELECT, UPDATE, INSERT ON TABLE public."Limites" TO authenticated;
GRANT SELECT, UPDATE ON TABLE public."Avisos" TO authenticated;

DROP POLICY IF EXISTS cold_ghost_limites_company ON public."Limites";
CREATE POLICY cold_ghost_limites_company
  ON public."Limites"
  FOR ALL TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public."Equipamento" AS equipment
      JOIN public."Company" AS company ON company.id_company = equipment.id_company
      JOIN public."Login" AS login ON login.id_login = company.id_login
      WHERE equipment.id_equipamento = "Limites".id_equipamento
        AND lower(login.email) = lower((SELECT auth.jwt() ->> 'email'))
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1
      FROM public."Equipamento" AS equipment
      JOIN public."Company" AS company ON company.id_company = equipment.id_company
      JOIN public."Login" AS login ON login.id_login = company.id_login
      WHERE equipment.id_equipamento = "Limites".id_equipamento
        AND lower(login.email) = lower((SELECT auth.jwt() ->> 'email'))
    )
  );

DROP POLICY IF EXISTS cold_ghost_avisos_company ON public."Avisos";
CREATE POLICY cold_ghost_avisos_company
  ON public."Avisos"
  FOR ALL TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public."Equipamento" AS equipment
      JOIN public."Company" AS company ON company.id_company = equipment.id_company
      JOIN public."Login" AS login ON login.id_login = company.id_login
      WHERE equipment.id_equipamento = "Avisos".id_equipamento
        AND lower(login.email) = lower((SELECT auth.jwt() ->> 'email'))
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1
      FROM public."Equipamento" AS equipment
      JOIN public."Company" AS company ON company.id_company = equipment.id_company
      JOIN public."Login" AS login ON login.id_login = company.id_login
      WHERE equipment.id_equipamento = "Avisos".id_equipamento
        AND lower(login.email) = lower((SELECT auth.jwt() ->> 'email'))
    )
  );

COMMIT;
